import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_PATH ? { executablePath: process.env.BROWSER_PATH } : {}) });
const base = process.env.QA_URL || 'http://localhost:4317';
const label = process.env.QA_LABEL || 'selection-rail';
const widths = (process.env.QA_WIDTHS || '320,390,768,1440').split(',').map(Number);
await mkdir('qa', { recursive: true });
const report = { url: base, browser: browser.version(), viewports: [], variants: {}, errors: [] };
const context = await browser.newContext();
const page = await context.newPage();
page.on('pageerror', e => report.errors.push(e.message));
page.on('console', msg => { if (msg.type() === 'error') report.errors.push(msg.text()); });
async function fits() { assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'horizontal overflow'); }
async function closeCity(keyboard = true) {
  if (keyboard) await page.keyboard.press('Escape');
  else await page.locator('.city-cancel').click();
  await page.locator('#city-dialog').waitFor({ state: 'hidden' });
  assert.equal(await page.locator('#city-trigger').evaluate(el => el === document.activeElement), true);
}
try {
  for (const width of widths) {
    await page.setViewportSize({ width, height: 1000 });
    const response = await page.goto(base, { waitUntil: 'networkidle' });
    assert.equal(response.status(), 200);
    await page.evaluate(() => document.fonts.ready);
    assert.equal(await page.locator('.motion-toggle,.parcel').count(), 0);
    const track = page.locator('.conveyor-track');
    await page.locator('.contact-panel').scrollIntoViewIfNeeded();
    await page.waitForFunction(() => document.querySelector('.production-line').classList.contains('is-offscreen'));
    assert.equal(await track.evaluate(el => getComputedStyle(el).animationPlayState), 'paused', 'offscreen rail pauses');
    await page.locator('.production-line').scrollIntoViewIfNeeded();
    await page.waitForFunction(() => !document.querySelector('.production-line').classList.contains('is-offscreen'));
    assert.equal(await track.evaluate(el => getComputedStyle(el).animationPlayState), 'running');
    assert.equal(await track.evaluate(el => getComputedStyle(el).animationDuration), '32s');
    const start = await track.evaluate(el => getComputedStyle(el).transform);
    await page.waitForTimeout(200);
    assert.notEqual(await track.evaluate(el => getComputedStyle(el).transform), start);
    // Pause only the screenshot sampling, then immediately resume the real animation.
    await track.evaluate(el => el.getAnimations().forEach(a => a.pause()));
    await page.locator('.production-line').screenshot({ path: `qa/${label}-${width}-rail.png` });
    await track.evaluate(el => el.getAnimations().forEach(a => a.play()));
    await page.locator('.contact-panel').scrollIntoViewIfNeeded();
    await page.waitForTimeout(850);
    await fits();
    const cards = await page.locator('.project-card').evaluateAll(els => els.map(el => { const r=el.getBoundingClientRect();return { top:r.top, left:r.left, width:r.width, height:r.height }; }));
    assert.equal(Math.abs(cards[0].top - cards[1].top) < 2, width >= 768, 'card columns');
    assert.ok(cards.every(c => c.height >= 100));
    await page.locator('button.form-button').click();
    assert.equal(await page.locator('#city-trigger').evaluate(el => el === document.activeElement), true);
    assert.equal(await page.locator('#city-error').isVisible(), true);
    await page.locator('#city-trigger').click();
    const dialog = page.locator('#city-dialog');
    await page.waitForTimeout(300);
    assert.equal(await page.locator('#city-search').evaluate(el => el === document.activeElement), true);
    assert.equal(await page.locator('.city-option').count(), 81);
    const box = await dialog.boundingBox();
    assert.ok(box.x >= -1 && box.y >= -1 && box.x + box.width <= width + 1 && box.y + box.height <= 1001, 'dialog fits viewport');
    if (width < 768) assert.ok(Math.abs(box.y + box.height - 1000) < 2, 'mobile bottom sheet');
    await page.screenshot({ path: `qa/${label}-${width}-city.png` });
    for (const [query, city] of [['istanbul','İstanbul'],['İZMİR','İzmir'],['sanliurfa','Şanlıurfa'],['AGRI','Ağrı']]) {
      await page.locator('#city-search').fill(query);
      assert.equal(await page.locator('.city-option').count(), 1);
      assert.equal(await page.locator('.city-option').getAttribute('data-city'), city);
      assert.ok(Math.abs((await dialog.boundingBox()).height - box.height) < 1, 'search must not resize dialog');
    }
    await page.locator('#city-search').fill('Atlantis');
    assert.equal(await page.locator('.city-empty').isVisible(), true);
    assert.equal(await page.locator('.city-option').count(), 0);
    assert.equal(await page.locator('#city').inputValue(), '');
    await page.locator('#city-search').fill('izmir');
    await page.locator('#city-search').press('Enter');
    await dialog.waitFor({ state: 'hidden' });
    assert.equal(await page.locator('#city').inputValue(), 'İzmir');
    assert.equal(await page.locator('#city-value').innerText(), 'İzmir');
    await page.locator('.project-card').nth(1).click();
    assert.equal(await page.locator('input[name=project]:checked').inputValue(), 'Ticari ve endüstriyel çatı GES');
    assert.equal(await page.locator('#selection-summary span').innerText(), 'İzmir · Ticari çatı');
    await page.locator('#city-trigger').click();
    await page.locator('#city-search').fill('ankara');
    await closeCity(false);
    assert.equal(await page.locator('#city').inputValue(), 'İzmir');
    await page.locator('#city-trigger').focus();
    await page.keyboard.press('Enter');
    assert.equal(await dialog.evaluate(el => getComputedStyle(el).transitionDuration), '0s', 'keyboard dialog is instant');
    await page.locator('#city-search').press('ArrowDown');
    assert.equal(await page.locator('.city-option').first().evaluate(el => el === document.activeElement), true);
    await page.keyboard.press('End');
    assert.equal(await page.locator('.city-option').last().evaluate(el => el === document.activeElement), true);
    await page.keyboard.press('Tab');
    assert.equal(await page.locator('#city-dialog').evaluate(el => el.contains(document.activeElement)), true, 'native focus containment');
    await closeCity();
    await page.locator('.contact-panel').screenshot({ path: `qa/${label}-${width}-form.png` });
    await page.locator('button.form-button').click();
    assert.equal(await page.locator('#brief-result').isVisible(), true);
    const message = await page.locator('#brief-message').innerText();
    const whatsapp = new URL(await page.locator('#whatsapp-link').getAttribute('href'));
    assert.equal(whatsapp.searchParams.get('text'), message);
    assert.match(message, /İzmir.*Ticari ve endüstriyel çatı GES/);
    await page.locator('#edit-brief').click();
    assert.equal(await page.locator('#city').inputValue(), 'İzmir');
    assert.equal(await page.locator('input[name=project]:checked').inputValue(), 'Ticari ve endüstriyel çatı GES');
    await fits();
    report.viewports.push({ width, overflow: false, columns: width >= 768 ? 2 : 1, cityDialog: { width: box.width, height: box.height, bottomSheet: width < 768 }, turkishSearch: true, cancellation: true, keyboard: true, message: true, rail: '32s; runs when visible; pauses offscreen' });
    console.log(`${width}px passed`);
  }
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto(base, { waitUntil: 'networkidle' });
  await page.locator('.production-line').scrollIntoViewIfNeeded();
  assert.equal(await page.locator('.conveyor-track').evaluate(el => getComputedStyle(el).animationName), 'none');
  assert.equal(await page.locator('.conveyor-group').nth(1).isVisible(), false);
  assert.equal(await page.locator('.conveyor-object:visible').count(), 5);
  await fits();
  await page.locator('.production-line').screenshot({ path: `qa/${label}-reduced-rail.png` });
  await page.locator('#city-trigger').click();
  assert.equal(await page.locator('#city-dialog').evaluate(el => getComputedStyle(el).transform), 'none');
  await closeCity();
  report.variants.reducedMotion = true;
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  const touch = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, deviceScaleFactor: 3 });
  const mobile = await touch.newPage();
  await mobile.goto(base, { waitUntil: 'networkidle' });
  await mobile.locator('#city-trigger').tap();
  await mobile.locator('#city-search').fill('sanliurfa');
  await mobile.locator('.city-option').tap();
  await mobile.locator('#city-dialog').waitFor({ state: 'hidden' });
  await mobile.locator('.project-card').last().tap();
  assert.equal(await mobile.locator('#selection-summary span').innerText(), 'Şanlıurfa · Tarımsal sulama');
  await mobile.locator('#city-trigger').tap();
  await mobile.setViewportSize({ width: 390, height: 420 });
  await mobile.waitForTimeout(300);
  const small = await mobile.locator('#city-dialog').boundingBox();
  assert.ok(small.y >= -1 && small.y + small.height <= 421, 'short viewport dialog fits');
  report.variants.touch = 'Chromium touch emulation; selection and short viewport passed';
  await touch.close();
  const nojs = await browser.newContext({ javaScriptEnabled: false, viewport: { width: 320, height: 844 } });
  const staticPage = await nojs.newPage();
  await staticPage.goto(base, { waitUntil: 'networkidle' });
  assert.equal(await staticPage.locator('#brief-form').isVisible(), false);
  assert.equal(await staticPage.locator('.official-application a').isVisible(), true);
  assert.equal(await staticPage.locator('.conveyor-object:visible').count(), 5);
  assert.equal(await staticPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await staticPage.locator('.production-line').scrollIntoViewIfNeeded();
  await staticPage.locator('.conveyor-object img').evaluateAll(images => Promise.all(images.map(image => image.decode())));
  await staticPage.locator('.production-line').screenshot({ path: `qa/${label}-no-js.png` });
  report.variants.noJavaScript = true;
  await nojs.close();
  // Native video remains lazy; do not transmit to YouTube during this interaction test.
  await page.route('https://www.youtube-nocookie.com/**', route => route.fulfill({ status: 200, contentType: 'text/html', body: '<title>Video test</title>' }));
  await page.locator('[data-video]').first().focus();
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#video-dialog').evaluate(el => el.open), true);
  await page.keyboard.press('Escape');
  await page.locator('iframe').waitFor({ state: 'detached' });
  report.variants.videoModal = 'passed; external playback not tested';
  assert.deepEqual(report.errors, []);
  report.status = 'passed';
} catch (error) {
  report.status = 'failed'; report.failure = error.stack;
  console.error(error); process.exitCode = 1;
  await page.screenshot({ path: `qa/${label}-failure.png`, fullPage: true }).catch(() => {});
} finally {
  await writeFile(`qa/${label}-report.json`, JSON.stringify(report, null, 2)+'\n');
  console.log(JSON.stringify(report));
  await browser.close();
}
